import type { AppState } from './storage';
import { migrateState } from './storage.ts';
import { assertCloudVersion } from './persistence.ts';

const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY,
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID,
  measurementId: process.env.NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID,
};

export type FirebaseUser = {
  uid: string;
  displayName: string | null;
  email: string | null;
  photoURL: string | null;
  isAnonymous: boolean;
};

export const firebaseConfigured = Boolean(config.apiKey && config.projectId && config.appId);

let servicesPromise: Promise<{
  auth: import('firebase/auth').Auth;
  db: import('firebase/firestore').Firestore;
}> | null = null;

async function getServices() {
  if (!firebaseConfigured) throw new Error('Firebase no está configurado');
  if (servicesPromise) return servicesPromise;

  servicesPromise = (async () => {
    const [{ initializeApp, getApps }, authSdk, firestoreSdk] = await Promise.all([
      import('firebase/app'),
      import('firebase/auth'),
      import('firebase/firestore'),
    ]);
    const app = getApps()[0] ?? initializeApp(config);
    const auth = authSdk.getAuth(app);
    await authSdk.setPersistence(auth, authSdk.browserLocalPersistence);

    let db;
    try {
      db = firestoreSdk.initializeFirestore(app, {
        ignoreUndefinedProperties: true,
        localCache: firestoreSdk.persistentLocalCache({
          tabManager: firestoreSdk.persistentMultipleTabManager(),
        }),
      });
    } catch {
      db = firestoreSdk.getFirestore(app);
    }

    if (config.measurementId) {
      void import('firebase/analytics').then(async ({ getAnalytics, isSupported }) => {
        if (await isSupported()) getAnalytics(app);
      }).catch(() => undefined);
    }

    return { auth, db };
  })().catch((error) => { servicesPromise = null; throw error; });

  return servicesPromise;
}

export async function subscribeToAuth(onChange: (user: FirebaseUser | null) => void) {
  if (!firebaseConfigured) {
    onChange(null);
    return () => undefined;
  }
  const [{ auth }, { onAuthStateChanged }] = await Promise.all([getServices(), import('firebase/auth')]);
  return onAuthStateChanged(auth, (user) => onChange(user ? {
    uid: user.uid,
    displayName: user.displayName,
    email: user.email,
    photoURL: user.photoURL,
    isAnonymous: user.isAnonymous,
  } : null));
}

export async function signInWithGoogle(): Promise<FirebaseUser> {
  const [{ auth }, { GoogleAuthProvider, signInWithPopup }] = await Promise.all([getServices(), import('firebase/auth')]);
  const provider = new GoogleAuthProvider();
  provider.setCustomParameters({ prompt: 'select_account' });
  const { user } = await signInWithPopup(auth, provider);
  return { uid: user.uid, displayName: user.displayName, email: user.email, photoURL: user.photoURL, isAnonymous: user.isAnonymous };
}

export async function signOutFirebase() {
  const [{ auth }, { signOut }] = await Promise.all([getServices(), import('firebase/auth')]);
  await signOut(auth);
}

export async function loadFromFirebase(expectedUid: string): Promise<AppState | null> {
  if (!firebaseConfigured) throw new Error('Firebase no está configurado');
  const [{ auth, db }, { doc, getDocFromServer }] = await Promise.all([getServices(), import('firebase/firestore')]);
  if (!auth.currentUser || auth.currentUser.isAnonymous || auth.currentUser.uid !== expectedUid) throw new Error('La cuenta activa ha cambiado');
  const snapshot = await getDocFromServer(doc(db, 'users', expectedUid, 'appState', 'main'));
  if (!snapshot.exists()) return null;
  return migrateState(snapshot.data());
}

// JSON data also strips optional undefined fields generated by plan migrations.
export function firebasePayload(state: AppState): AppState {
  return JSON.parse(JSON.stringify(state));
}

export async function syncToFirebase(state: AppState, expectedUid: string, expectedVersion: string | null): Promise<void> {
  const [{ auth, db }, { doc, runTransaction }] = await Promise.all([getServices(), import('firebase/firestore')]);
  if (!auth.currentUser || auth.currentUser.isAnonymous || auth.currentUser.uid !== expectedUid) {
    throw new Error('La cuenta activa ha cambiado');
  }
  const reference = doc(db, 'users', expectedUid, 'appState', 'main');
  await runTransaction(db, async (transaction) => {
    const current = await transaction.get(reference);
    assertCloudVersion(current.exists() ? current.data().updatedAt ?? null : null, expectedVersion);
    transaction.set(reference, firebasePayload(state));
  });
}
